#!/bin/bash
# Installation with the Helm CLI. Everything except the chart version is optional: without values
# the chart deploys Guacamole with an embedded PostgreSQL and generated passwords.
set -euo pipefail

VERSION=0.1.1
NAMESPACE=guacamole

# Optional: provide your own Opaque Secret for the guacadmin password instead of a generated one
# (set auth.admin.existingSecret=guacamole-admin below).
# kubectl create namespace "$NAMESPACE"
# kubectl -n "$NAMESPACE" create secret generic guacamole-admin --from-literal=password='...'

# --wait fails if an init job fails; --atomic rolls back a failed install/upgrade.
helm upgrade --install guacamole oci://ghcr.io/alirionx/charts/guacamole --version "$VERSION" \
  -n "$NAMESPACE" --create-namespace --wait --atomic --timeout 10m \
  --set ingress.enabled=true \
  --set ingress.className=traefik \
  --set 'ingress.hosts[0]=guacamole.example.com' \
  --set ingress.tls.enabled=true

# Smoke test: login page and database authentication
helm test guacamole -n "$NAMESPACE" --logs

# guacadmin password (generated by the secret init job)
kubectl -n "$NAMESPACE" get secret guacamole-admin -o jsonpath='{.data.password}' | base64 -d; echo
